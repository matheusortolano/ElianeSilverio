// Contatos só viram links depois de receberem valores válidos.
// Nunca direcionar a números fictícios.

export function contactHref(
  kind: keyof SiteContent["contact"],
): string | undefined {
  const value = siteContent.contact[kind].trim();

  if (!value || value.startsWith("[")) {
    return undefined;
  }

  if (kind === "whatsapp") {
    const digits = value.replace(/\D/g, "");

    return /^\d{10,15}$/.test(digits)
      ? `https://wa.me/${digits}`
      : undefined;
  }

  if (kind === "email") {
    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value)
      ? `mailto:${value}`
      : undefined;
  }

  try {
    const url = new URL(value);

    return url.protocol === "https:" &&
      /(^|\.)linkedin\.com$/.test(url.hostname)
      ? url.href
      : undefined;
  } catch {
    return undefined;
  }
}